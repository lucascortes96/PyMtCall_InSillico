"""Benchmark PyMtCall and Signac against a high-depth synthetic truth dataset.

This is a separate workflow from InSillico.py. It imports that script's cell
AnnData helper, PyMtCall wrapper, and variant-name conversion, while keeping all
benchmark counts and Signac outputs under TruthBenchmark/ so it does not replace
the other workflow's Files/, Signac/, or PyStats/ data.

The truth dataset contains 1,000 known variants at 1,000 positions, measured in
1,000 fixed cells. High-depth raw VAFs define the reference values. Each lower-
depth dataset is generated by independent random read thinning of those same
high-depth counts.
"""

from __future__ import annotations

import subprocess
import shutil
from pathlib import Path

import anndata as ad
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy import sparse

import InSillico as source_workflow


ROOT = Path(__file__).resolve().parent
OUTPUT_ROOT = ROOT / "TruthBenchmark"
CELL_COUNT = 1_000
VARIANT_COUNT = 1_000
HIGH_DEPTH_MEAN = 1_000
DEPTH_TARGETS = (150, 100, 50, 20, 10)
DROPOUT_RATE = 0.05
VAF_BETA_ALPHA = 1.0
STRAND_BETA_ALPHA = 10.0
RANDOM_SEED = 2026
BASES = np.array(list("ACGT"))


def generate_truth_dataset(
    seed: int = RANDOM_SEED,
) -> tuple[list[str], np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Generate high-depth counts and the raw variant/VAF truth.

    Every simulated position has one known alternate allele and one randomly
    assigned, different reference allele. The true cell-specific allele fraction
    is drawn from Beta(1, 1), i.e. uniformly across the 0-to-1 range. Per-cell
    sequencing depth is lognormal-Poisson with
    mean approximately 1,000 reads in every cell. Reads are split between
    strands using Beta(10, 10) strand fractions. The configurable whole-cell
    dropout rate defaults to zero for this truth benchmark.

    Returns barcodes, positions, references, alternates, a positions-by-cells-by-
    (ref-forward, ref-reverse, alt-forward, alt-reverse) count array, and the
    observed high-depth raw VAF array (positions by cells).
    """
    rng = np.random.default_rng(seed)
    positions = np.arange(1, VARIANT_COUNT + 1, dtype=np.int32)
    barcodes = [
        "".join(rng.choice(BASES, size=16)) + "-1"
        for _ in range(CELL_COUNT)
    ]
    # Resolve the extremely unlikely barcode collision deterministically.
    while len(set(barcodes)) < CELL_COUNT:
        seen: set[str] = set()
        for index, barcode in enumerate(barcodes):
            if barcode in seen:
                barcodes[index] = "".join(rng.choice(BASES, size=16)) + "-1"
            seen.add(barcodes[index])
    # PyMtCall aligns its count-matrix columns lexicographically; keep the
    # AnnData cell order identical so returned per-cell VAFs map to truth cells.
    barcodes.sort()

    references = rng.choice(BASES, size=VARIANT_COUNT)
    alternates = np.empty(VARIANT_COUNT, dtype="U1")
    for index, reference in enumerate(references):
        alternates[index] = rng.choice(BASES[BASES != reference])

    dropout_cells = rng.random(CELL_COUNT) < DROPOUT_RATE
    # Parameterize the lognormal so its arithmetic mean is HIGH_DEPTH_MEAN.
    depth_sigma = 0.2
    cell_mean_depth = np.exp(
        np.log(HIGH_DEPTH_MEAN) - 0.5 * depth_sigma**2
        + rng.normal(0, depth_sigma, size=CELL_COUNT)
    )
    total_depth = rng.poisson(cell_mean_depth[None, :], size=(VARIANT_COUNT, CELL_COUNT))
    true_allele_fraction = rng.beta(
        VAF_BETA_ALPHA, VAF_BETA_ALPHA, size=(VARIANT_COUNT, CELL_COUNT)
    )
    alternate_depth = rng.binomial(total_depth, true_allele_fraction)
    reference_depth = total_depth - alternate_depth

    strand_fraction = rng.beta(
        STRAND_BETA_ALPHA, STRAND_BETA_ALPHA, size=total_depth.shape
    )
    # Shared bias at a site/cell models strand-specific library or mapping bias.
    ref_forward = rng.binomial(reference_depth, strand_fraction)
    alt_forward = rng.binomial(alternate_depth, strand_fraction)
    ref_reverse = reference_depth - ref_forward
    alt_reverse = alternate_depth - alt_forward

    for counts in (ref_forward, ref_reverse, alt_forward, alt_reverse):
        counts[:, dropout_cells] = 0

    raw_counts = np.stack(
        (ref_forward, ref_reverse, alt_forward, alt_reverse), axis=-1
    ).astype(np.int32, copy=False)
    observed_total = raw_counts.sum(axis=-1)
    raw_vaf = np.divide(
        raw_counts[:, :, 2] + raw_counts[:, :, 3],
        observed_total,
        out=np.zeros_like(observed_total, dtype=float),
        where=observed_total > 0,
    )
    return barcodes, positions, references, alternates, raw_counts, raw_vaf


def downsample_reads(
    raw_counts: np.ndarray,
    target_depth: int,
    seed: int,
) -> np.ndarray:
    """Independently retain each high-depth read with target/mean probability."""
    rng = np.random.default_rng(seed)
    keep_probability = target_depth / HIGH_DEPTH_MEAN
    return rng.binomial(raw_counts, keep_probability).astype(np.int32, copy=False)


def write_mgatk_files(
    input_dir: Path,
    barcodes: list[str],
    positions: np.ndarray,
    references: np.ndarray,
    alternates: np.ndarray,
    counts: np.ndarray,
) -> None:
    """Write one downsampled dataset as headerless MGATK-format text files."""
    input_dir.mkdir(parents=True, exist_ok=True)
    ref_forward, ref_reverse, alt_forward, alt_reverse = (
        counts[:, :, column] for column in range(4)
    )
    total_coverage = counts.sum(axis=2)
    barcode_array = np.asarray(barcodes)

    for base in "ACGT":
        ref_positions = np.flatnonzero(references == base)
        alt_positions = np.flatnonzero(alternates == base)
        site_positions = np.union1d(ref_positions, alt_positions)
        if not len(site_positions):
            base_counts_forward = np.zeros((0, len(barcodes)), dtype=np.int32)
            base_counts_reverse = np.zeros_like(base_counts_forward)
        else:
            is_reference = references[site_positions] == base
            is_alternate = alternates[site_positions] == base
            base_counts_forward = (
                ref_forward[site_positions] * is_reference[:, None]
                + alt_forward[site_positions] * is_alternate[:, None]
            )
            base_counts_reverse = (
                ref_reverse[site_positions] * is_reference[:, None]
                + alt_reverse[site_positions] * is_alternate[:, None]
            )

        pd.DataFrame(
            {
                0: np.repeat(positions[site_positions], len(barcodes)),
                1: np.tile(barcode_array, len(site_positions)),
                2: base_counts_forward.ravel(),
                3: base_counts_reverse.ravel(),
            }
        ).to_csv(input_dir / f"mgatk.{base}.txt", index=False, header=False)

    pd.DataFrame(
        {
            0: np.repeat(positions, len(barcodes)),
            1: np.tile(barcode_array, len(positions)),
            2: total_coverage.ravel(),
        }
    ).to_csv(input_dir / "mgatk.coverage.txt", index=False, header=False)
    pd.DataFrame({0: positions, 1: references}).to_csv(
        input_dir / "chrM_refAllele.txt", index=False, header=False
    )


def run_signac(input_dir: Path, output_dir: Path) -> Path:
    """Run the existing Signac R script into this benchmark's isolated folder."""
    rscript = shutil.which("Rscript")
    if rscript is None:
        raise RuntimeError("Rscript was not found on PATH; install R and Signac first.")
    output_dir.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            rscript,
            str(ROOT / "signac_script.R"),
            str(input_dir),
            str(source_workflow.SIGNAC_LOW_COVERAGE_THRESHOLD),
            str(output_dir),
        ],
        check=True,
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    return output_dir


def make_minimal_adata(barcodes: list[str]) -> ad.AnnData:
    """Make the barcode-aligned AnnData input needed by the caller wrapper."""
    return ad.AnnData(
        X=sparse.csr_matrix((len(barcodes), 0)),
        obs=pd.DataFrame(index=pd.Index(barcodes, name="barcode")),
    )


def calculate_confusion(truth: np.ndarray, prediction: np.ndarray) -> dict[str, int | float]:
    """Return confusion counts and common classification metrics for two masks."""
    truth = np.asarray(truth, dtype=bool)
    prediction = np.asarray(prediction, dtype=bool)
    tp = int(np.sum(truth & prediction))
    fp = int(np.sum(~truth & prediction))
    fn = int(np.sum(truth & ~prediction))
    tn = int(np.sum(~truth & ~prediction))
    return calculate_confusion_from_counts(tp, fp, fn, tn)


def calculate_confusion_from_counts(
    tp: int, fp: int, fn: int, tn: int
) -> dict[str, int | float]:
    """Calculate classification metrics from pre-aggregated confusion counts."""
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    specificity = tn / (tn + fp) if tn + fp else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "tn": tn,
        "precision": precision,
        "recall": recall,
        "specificity": specificity,
        "f1": f1,
    }


def evaluate_depth(
    target_depth: int,
    barcodes: list[str],
    positions: np.ndarray,
    references: np.ndarray,
    alternates: np.ndarray,
    truth_counts: np.ndarray,
    truth_vaf: np.ndarray,
) -> tuple[list[dict[str, int | float | str]], list[dict[str, int | float | str]]]:
    """Run both callers at one depth and score variant and cell calls against truth."""
    run_dir = OUTPUT_ROOT / f"depth_{target_depth}"
    input_dir = run_dir / "input"
    downsampled_counts = downsample_reads(
        truth_counts, target_depth, RANDOM_SEED + target_depth
    )
    write_mgatk_files(
        input_dir, barcodes, positions, references, alternates, downsampled_counts
    )

    adata = source_workflow.run_python_caller(input_dir, make_minimal_adata(barcodes))
    signac_dir = run_signac(input_dir, run_dir / "signac")
    candidate_stats, _, signac_vaf = source_workflow.load_signac_results(
        signac_dir, adata.obs_names
    )

    truth_names = {
        f"{position}{reference}>{alternate}"
        for position, reference, alternate in zip(positions, references, alternates)
    }
    truth_name_to_index = {
        f"{position}{reference}>{alternate}": index
        for index, (position, reference, alternate) in enumerate(
            zip(positions, references, alternates)
        )
    }
    python_variant_names = list(adata.uns.get("variant_names", []))
    python_index = {
        source_workflow.py_variant_to_signac_name(name): index
        for index, name in enumerate(python_variant_names)
    }
    python_calls = set(python_index)

    # Score variant-level calls over every substitution considered by Signac,
    # including the 2,000 non-truth alternate substitutions per position.
    candidate_names = set(candidate_stats["variant"].astype(str)) | python_calls | truth_names
    ordered_candidates = sorted(candidate_names)

    py_vaf_lookup = {
        name: np.asarray(adata.obsm["variant_vaf"][:, index], dtype=float)
        for name, index in python_index.items()
    }
    signac_vaf_lookup = {
        name: signac_vaf[name].to_numpy(dtype=float)
        for name in signac_vaf.columns
    }

    # Cell-level positive truth is defined by alternate reads observed in the
    # unthinned high-depth data. Dropout cells therefore have true VAF/call zero.
    truth_cell_calls = (truth_counts[:, :, 2] + truth_counts[:, :, 3]) > 0
    summary_rows: list[dict[str, int | float | str]] = []
    variant_rows: list[dict[str, int | float | str]] = []

    for method in ("PyMtCall", "Signac"):
        predicted_vaf = np.zeros_like(truth_vaf)
        per_variant_lookup = py_vaf_lookup if method == "PyMtCall" else signac_vaf_lookup

        for variant_index, variant_name in enumerate(
            f"{position}{reference}>{alternate}"
            for position, reference, alternate in zip(positions, references, alternates)
        ):
            values = per_variant_lookup.get(variant_name)
            if values is not None:
                predicted_vaf[variant_index] = values
                predicted_cell_calls = values > 0
            else:
                predicted_cell_calls = np.zeros(CELL_COUNT, dtype=bool)

            cell_metrics = calculate_confusion(
                truth_cell_calls[variant_index], predicted_cell_calls
            )
            vaf_error = values - truth_vaf[variant_index] if values is not None else -truth_vaf[variant_index]
            variant_rows.append({
                "depth_target": target_depth,
                "method": method,
                "variant": variant_name,
                "truth_median_raw_vaf": float(np.median(truth_vaf[variant_index])),
                "predicted_median_vaf": float(np.median(predicted_vaf[variant_index])),
                "vaf_mae_vs_high_depth_truth": float(np.mean(np.abs(vaf_error))),
                "vaf_rmse": float(np.sqrt(np.mean(vaf_error**2))),
                "cell_tp": cell_metrics["tp"],
                "cell_fp": cell_metrics["fp"],
                "cell_fn": cell_metrics["fn"],
                "cell_tn": cell_metrics["tn"],
                "cell_call_recall": cell_metrics["recall"],
            })

        cell_tp = cell_fp = cell_fn = cell_tn = 0
        for variant_name in ordered_candidates:
            values = per_variant_lookup.get(variant_name)
            called_cells = values > 0 if values is not None else np.zeros(CELL_COUNT, dtype=bool)
            truth_cells = (
                truth_cell_calls[truth_name_to_index[variant_name]]
                if variant_name in truth_name_to_index
                else np.zeros(CELL_COUNT, dtype=bool)
            )
            cell_tp += int(np.sum(truth_cells & called_cells))
            cell_fp += int(np.sum(~truth_cells & called_cells))
            cell_fn += int(np.sum(truth_cells & ~called_cells))
            cell_tn += int(np.sum(~truth_cells & ~called_cells))
        cell_metrics = calculate_confusion_from_counts(cell_tp, cell_fp, cell_fn, cell_tn)
        vaf_error = predicted_vaf - truth_vaf
        summary_rows.append({
            "depth_target": target_depth,
            "mean_observed_coverage": float(downsampled_counts.sum(axis=2).mean()),
            "method": method,
            "true_variant_count": len(truth_names),
            "variant_candidate_count": len(candidate_names),
            **{
                f"cell_{key}": value
                for key, value in cell_metrics.items()
                if key != "recall"
            },
            "cell_call_recall": cell_metrics["recall"],
            "vaf_mae_vs_high_depth_truth": float(np.mean(np.abs(vaf_error))),
            "vaf_rmse": float(np.sqrt(np.mean(vaf_error**2))),
            "vaf_bias_method_minus_truth": float(np.mean(vaf_error)),
            "vaf_pearson_r": (
                float(np.corrcoef(truth_vaf.ravel(), predicted_vaf.ravel())[0, 1])
                if np.std(truth_vaf) > 0 and np.std(predicted_vaf) > 0 else np.nan
            ),
        })

    return summary_rows, variant_rows


def save_accuracy_plot(summary: pd.DataFrame) -> None:
    """Plot cell-level classification metrics and VAF error by depth category."""
    metric_specs = (
        ("cell_precision", "Cell-call precision", (0, 1.02)),
        ("cell_call_recall", "Cell-call recall", (0, 1.02)),
        ("cell_specificity", "Cell-call specificity", (0, 1.02)),
        ("cell_f1", "Cell-call F1", (0, 1.02)),
        ("vaf_mae_vs_high_depth_truth", "VAF MAE vs high-depth truth", None),
    )
    figure, axes = plt.subplots(1, len(metric_specs), figsize=(17, 4))
    depths = sorted(summary["depth_target"].unique())
    depth_positions = {depth: index for index, depth in enumerate(depths)}
    for method, subset in summary.groupby("method"):
        subset = subset.sort_values("depth_target")
        positions = [depth_positions[depth] for depth in subset["depth_target"]]
        for axis, (column, _, _) in zip(axes, metric_specs):
            axis.plot(positions, subset[column], marker="o", label=method)

    depth_labels = [str(depth) for depth in depths]
    for axis, (_, title, limits) in zip(axes, metric_specs):
        axis.set_xticks(range(len(depths)), depth_labels)
        axis.set_xlabel("Target depth (reads per cell/site)")
        axis.set_title(title)
        axis.grid(alpha=0.25)
        if limits is not None:
            axis.set_ylim(*limits)
    axes[0].set_ylabel("Score")
    axes[-1].set_ylabel("Mean absolute VAF error")
    handles, labels = axes[0].get_legend_handles_labels()
    figure.legend(handles, labels, loc="upper center", ncol=len(labels))
    figure.tight_layout(rect=(0, 0, 1, 0.9))
    figure.savefig(OUTPUT_ROOT / "accuracy_by_depth.pdf", bbox_inches="tight")
    plt.close(figure)


def main() -> None:
    """Generate truth once, evaluate each read-depth target, and save reports."""
    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    barcodes, positions, references, alternates, truth_counts, truth_vaf = generate_truth_dataset()
    truth_variants = pd.DataFrame({
        "variant": [
            f"{position}{reference}>{alternate}"
            for position, reference, alternate in zip(positions, references, alternates)
        ],
        "position": positions,
        "reference": references,
        "alternate": alternates,
        "median_high_depth_raw_vaf": np.median(truth_vaf, axis=1),
        "mean_high_depth_raw_vaf": np.mean(truth_vaf, axis=1),
        "positive_cells_at_high_depth": np.sum(truth_counts[:, :, 2] + truth_counts[:, :, 3] > 0, axis=1),
    })
    truth_variants.to_csv(OUTPUT_ROOT / "truth_variants.csv", index=False)
    np.savez_compressed(
        OUTPUT_ROOT / "high_depth_truth_vaf.npz",
        vaf=truth_vaf,
        barcodes=np.asarray(barcodes),
        positions=positions,
    )

    all_summary_rows: list[dict[str, int | float | str]] = []
    all_variant_rows: list[dict[str, int | float | str]] = []
    for depth_target in DEPTH_TARGETS:
        print(f"Benchmarking target depth {depth_target} reads per cell/site")
        summary_rows, variant_rows = evaluate_depth(
            depth_target,
            barcodes,
            positions,
            references,
            alternates,
            truth_counts,
            truth_vaf,
        )
        all_summary_rows.extend(summary_rows)
        all_variant_rows.extend(variant_rows)

    summary = pd.DataFrame(all_summary_rows)
    summary.to_csv(OUTPUT_ROOT / "benchmark_summary.csv", index=False)
    pd.DataFrame(all_variant_rows).to_csv(
        OUTPUT_ROOT / "benchmark_per_variant.csv", index=False
    )
    save_accuracy_plot(summary)
    print(f"Benchmark outputs written to {OUTPUT_ROOT}")


if __name__ == "__main__":
    main()
